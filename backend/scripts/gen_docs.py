        "| `POSTGRES_PASSWORD` | خالی | گذرواژه‌ی PostgreSQL در پروفایل `postgres` |\n"
        "| `NODE_IMAGE`، `PYTHON_IMAGE`، `CADDY_IMAGE`، `POSTGRES_IMAGE` | تصاویر رسمی | برای استفاده از رجیستری دیگر |\n"
        "\n## متغیرهای سمت کلاینت\n\n"
        "| متغیر | کاربرد |\n|---|---|\n"
