LEVELS = [Level.READ_ONLY, Level.DEVELOPER, Level.OPERATOR, Level.APPROVAL_REQUIRED, Level.AUTONOMOUS]


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def type_name(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " \\| ".join(type_name(s) for s in schema["anyOf"])
    if schema.get("type") == "array":
        return f"array<{type_name(schema.get('items', {}))}>"
    if pattern := schema.get("pattern"):
        if pattern.startswith("^(") and pattern.endswith(")$"):
            return " \\| ".join(f"`{v}`" for v in pattern[2:-2].split("|"))
    return schema.get("type", "object")


def schema_table(schema: dict) -> str:
    properties = schema.get("properties", {})
    if not properties:
        return "بدون ورودی.\n"
    required = set(schema.get("required", []))
    rows = ["| ورودی | نوع | الزامی | پیش‌فرض | توضیح |", "|---|---|---|---|---|"]
    for name, prop in properties.items():
        default = "" if name in required or "default" not in prop else f"`{prop['default']!r}`"
        rows.append(
            f"| `{name}` | {type_name(prop)} | {'بله' if name in required else ''} | {default} "
            f"| {cell(prop.get('description', ''))} |"
        )
    return "\n".join(rows) + "\n"


def verdict(level: Level, kind: Kind, *, destructive: bool = False, sandboxed: bool = True, docker: bool = True) -> str:
    grant = GrantConfig(level=level, allow_docker=docker)
    try:
        result = decide(grant, kind, destructive="x" if destructive else "", sandboxed=sandboxed)
    except errors.PolicyDenied:
        return "رد"
    return "آزاد" if result.decision.value == "allow" else "تأیید"


