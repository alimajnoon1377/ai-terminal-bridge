LEVELS = [Level.READ_ONLY, Level.DEVELOPER, Level.OPERATOR, Level.APPROVAL_REQUIRED, Level.AUTONOMOUS]


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def type_name(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " \\| ".join(type_name(s) for s in schema["anyOf"])
    if schema.get("type") == "array":
        return f"array<{type_name(schema.get('items', {}))}>"
    if pattern := schema.get("pattern"):
        if pattern.startswith("^(") and pattern.endswith(")$"):
            return " \\| ".join(f"`{v}`" for v in pattern[2:-2].split("|"))
    return schema.get("type", "object")


def schema_table(schema: dict) -> str:
    properties = schema.get("properties", {})
    if not properties:
        return "No input.\n"
    required = set(schema.get("required", []))
    rows = ["| Input | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    for name, prop in properties.items():
        default = "" if name in required or "default" not in prop else f"`{prop['default']!r}`"
        rows.append(
            f"| `{name}` | {type_name(prop)} | {'yes' if name in required else ''} | {default} "
            f"| {cell(prop.get('description', ''))} |"
        )
    return "\n".join(rows) + "\n"


def verdict(level: Level, kind: Kind, *, destructive: bool = False, sandboxed: bool = True, docker: bool = True) -> str:
    grant = GrantConfig(level=level, allow_docker=docker)
    try:
        result = decide(grant, kind, destructive="x" if destructive else "", sandboxed=sandboxed)
    except errors.PolicyDenied:
        return "deny"
    return "allow" if result.decision.value == "allow" else "approval"


def tools_doc() -> str:
    builtin = {n: s for n, s in REGISTRY.items() if s.handler.__module__.startswith("atb.")}
    if set(builtin) != set(TOOL_NOTES):
        raise SystemExit(f"TOOL_NOTES is out of date: {sorted(set(builtin) ^ set(TOOL_NOTES))}")
    out = [BANNER, f"# Tools ({len(builtin)} tools)\n\n",
           "Every interface (MCP, REST, WebSocket, OpenAI format) runs these same tools under the same access policy. "
           "Unknown input is rejected. Each tool description is the text the model sees.\n\n",
           "## Decision matrix\n\n",
           "This table is generated from the `decide` function itself. Path rules, the allowed/denied command lists and "
           "the service list are applied separately, before it.\n\n",
           "| Operation | " + " | ".join(f"`{level.value}`" for level in LEVELS) + " |\n",
           "|---|" + "---|" * len(LEVELS) + "\n"]
    rows = [
        ("Read", Kind.READ, {}),
        ("Write a file", Kind.WRITE, {}),
        ("Destructive write", Kind.WRITE, {"destructive": True}),
        ("Run a command in the sandbox", Kind.EXEC, {}),
        ("Run a command without the sandbox", Kind.EXEC, {"sandboxed": False}),
        ("Destructive command", Kind.EXEC, {"destructive": True}),
        ("Control a service", Kind.SERVICE, {}),
        ("Stop/disable a service", Kind.SERVICE, {"destructive": True}),
        ("Control Docker (with allow_docker)", Kind.DOCKER, {}),
        ("Control Docker (without allow_docker)", Kind.DOCKER, {"docker": False}),
    ]
    for label, kind, options in rows:
        out.append(f"| {label} | " + " | ".join(verdict(level, kind, **options) for level in LEVELS) + " |\n")
    out.append(
        "\n- \"approval\" means the operation does not run until a human decides.\n"
        "- At the `autonomous` level, the `auto_approve_destructive` option also runs destructive operations without approval.\n"
        "- The `developer` level runs commands in the sandbox; the other levels do so only when `force_sandbox` is on. "
        "So in `operator`, `approval_required` and `autonomous`, path restrictions **do not apply to shell commands** "
        "unless `force_sandbox` is used.\n\n"
        "Default denied paths: " + ", ".join(f"`{g}`" for g in DEFAULT_DENY_GLOBS) + "\n\n"
        "## Tool list\n"
    )
    for name, spec in builtin.items():
        out.append(f"\n### `{name}`\n\n{spec.description}\n\n**Access:** {TOOL_NOTES[name]}\n\n{schema_table(spec.input_schema)}")
    out.append(
        "\n## Common responses\n\n"
        "- Error: `{\"error\": CODE, \"message\": ...}` (the codes are listed in [API.md](API.md)).\n"
        "- Approval needed: `{\"status\": \"approval_required\", \"approval_id\": ...}`; after approval, repeat **the same call with the same input**. "
        "An approval is single use and is voided if the file, the grant or the environment changes.\n"
        "- Long-running command: `{\"command_id\": ..., \"status\": \"running\", \"next_offset\": ...}`; continue with `get_command_output`.\n"
    )
    return "".join(out)


def auth_label(route: APIRoute) -> str:
    calls, stack = set(), [route.dependant]
    while stack:
        node = stack.pop()
        calls.add(node.call)
        stack.extend(node.dependencies)
    if admin_user in calls:
        return "administrator"
    if current_actor in calls:
        return "assistant or user"
    if current_user in calls:
        return "user"
    return "no authentication"


def api_doc() -> str:
    with tempfile.TemporaryDirectory() as data:
        app = create_app(Settings(data_dir=Path(data), static_dir="", _env_file=None))
        spec = app.openapi()
        app.state.services.db.engine.sync_engine.dispose()
    labels = {}
    for router in (admin.router, toolapi.router):
        for route in router.routes:
            if isinstance(route, APIRoute):
                for method in route.methods:
                    labels[(method.lower(), route.path)] = auth_label(route)
    out = [BANNER, "# API\n\n",
           "Base URL: the address of the bridge (default `http://127.0.0.1:8750`). Authentication: the `Authorization: Bearer TOKEN` header.\n\n"
           "- An **assistant** token (`atbag_...`) is created in the dashboard and can access only the tools.\n"
           "- A **user** token (`atbs_...`) is obtained from `/api/auth/login`. A regular user sees only their own servers and assistants; an administrator sees all of them.\n"
           "- Interactive schema: `/api/docs` (its front-end files are loaded from a CDN) and `/api/openapi.json`.\n"
           "- The maximum request body size is 8 MB.\n\n",
           "## HTTP\n\n| Method | Path | Access | Parameters / body |\n|---|---|---|---|\n"]
    schemas = spec.get("components", {}).get("schemas", {})
    for path, methods in spec["paths"].items():
        for method, operation in methods.items():
            inputs = [f"`{p['name']}`" for p in operation.get("parameters", []) if p["in"] == "query"]
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema", {})
            if ref := body.get("$ref"):
                model = schemas[ref.rsplit("/", 1)[-1]]
                required = set(model.get("required", []))
                inputs += [f"`{n}`{'*' if n in required else ''}" for n in model.get("properties", {})]
            elif body:
                inputs.append("tool input (JSON)")
            label = labels.get((method, path), "no authentication")
            out.append(f"| {method.upper()} | `{path}` | {label} | {', '.join(inputs)} |\n")
    out.append(
        "\n`*` marks a required field. Structure of a grant (`PUT .../grants/{server_id}`):\n\n"
        + schema_table(GrantConfig.model_json_schema())
        + "\nEach path rule: `{\"path\": \"/absolute/path\", \"mode\": \"rw\" | \"ro\"}`; the most specific rule wins.\n"
        "\n## MCP\n\n"
        "- **Streamable HTTP:** `POST /mcp` with an assistant token; stateless (no session). The Host header must be listed in `ATB_ALLOWED_HOSTS`.\n"
        "- **stdio:** `atb mcp-stdio` with the `ATB_URL` and `ATB_AGENT_TOKEN` variables; a proxy that forwards calls to the running bridge.\n"
        "- Client guide: [CLIENTS.md](CLIENTS.md).\n\n"
        "## WebSocket\n\n"
        "The token is sent in the **first message**, not in the URL. Close codes: `4401` invalid token, `4404` unknown server, `4400` invalid input.\n\n"
        "| Path | Access | Messages |\n|---|---|---|\n"
        "| `/api/ws/events` | user | send `{\"token\"}`; receive `ready`, then live events (activity, command output, approvals, emergency stop) |\n"
        "| `/api/ws/tools` | assistant or user | send `{\"token\"}`, then `{\"id\", \"tool\", \"arguments\"}`; receive `{\"id\", \"ok\", \"result\" \\| \"error\"}`; at most 8 concurrent calls |\n"
        "| `/api/ws/terminal/{server_id}` | user | send `{\"token\", \"cols\", \"rows\", \"session\"}`, then `{\"type\": \"input\", \"data\"}` or `{\"type\": \"resize\", \"cols\", \"rows\"}`; output is binary |\n"
        "\n## Error codes\n\n| Code | HTTP |\n|---|---|\n"
    )
    for item in [errors.BridgeError, *errors.BridgeError.__subclasses__()]:
        out.append(f"| `{item.code}` | {item.status} |\n")
    return "".join(out)


def config_doc() -> str:
    if set(Settings.model_fields) != set(SETTING_NOTES):
        raise SystemExit(f"SETTING_NOTES is out of date: {sorted(set(Settings.model_fields) ^ set(SETTING_NOTES))}")
    out = [BANNER, "# Configuration\n\n",
           "The bridge reads its settings from environment variables (or a `.env` file in the directory it is run from).\n\n",
           "| Variable | Default | Description |\n|---|---|---|\n"]
    for name, field in Settings.model_fields.items():
        default = str(field.default)
        out.append(f"| `ATB_{name.upper()}` | {f'`{cell(default)}`' if default else 'empty'} | {SETTING_NOTES[name]} |\n")
    out.append(
        "\n## Docker Compose variables (in `.env`)\n\n"
        "| Variable | Default | Description |\n|---|---|---|\n"
        "| `ATB_BIND` | `127.0.0.1` | address on which the port is published on the Docker host |\n"
        "| `ATB_PUBLISH_PORT` | `8750` | host port |\n"
        "| `ATB_DOMAIN` | empty | domain for the `https` profile |\n"
        "| `ATB_EXTRA_HOSTS` | empty | additional host names allowed for `/mcp`, for example `192.168.1.10:*` |\n"
        "| `ATB_SUBNET` | `172.31.250.0/24` | internal Compose subnet; only the proxy inside it is trusted |\n"
        "| `POSTGRES_PASSWORD` | empty | PostgreSQL password for the `postgres` profile |\n"
        "| `NODE_IMAGE`, `PYTHON_IMAGE`, `CADDY_IMAGE`, `POSTGRES_IMAGE` | official images | for using another registry |\n"
        "\n## Client-side variables\n\n"
        "| Variable | Use |\n|---|---|\n"
        "| `ATB_URL` | bridge address for `atb mcp-stdio`, `atb call` and the example script |\n"
        "| `ATB_AGENT_TOKEN` | assistant token for the same |\n"
        "| `ATB_NEW_PASSWORD` | password for `atb create-user` without an interactive prompt |\n"
    )
    return "".join(out)


def generate() -> dict[Path, str]:
    return {DOCS / "TOOLS.md": tools_doc(), DOCS / "API.md": api_doc(), DOCS / "CONFIG.md": config_doc()}


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in generate().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print(f"out of date: {', '.join(stale)}; run python backend/scripts/gen_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
